import AppKit
import Observation
import IdeaCore

/// v2 剪贴板历史的共享状态 + 监听（design §11，product §10.2）。
/// 来源 App 只在读剪贴板的那一刻用来判断「不记录名单」，不保存（D23④）。
@Observable @MainActor
public final class ClipboardModel {
    public private(set) var store: ClipboardStore
    /// 按时间倒序；store 的镜像，供 SwiftUI 观察
    public private(set) var items: [ClipItem] = []

    /// 记录开关（偏好设置「记录剪贴板」= 主窗口「暂停 / 继续记录」）
    public var enabled: Bool {
        didSet { defaults.set(enabled, forKey: Keys.enabled) }
    }
    public var limit: Int {
        didSet {
            let c = ClipboardStore.clampLimit(limit)
            if c != limit { limit = c }
            defaults.set(limit, forKey: Keys.limit)
            store.setLimit(limit)
            items = store.items
        }
    }
    /// 不记录这些 App（bundle id）
    public var excluded: [String] {
        didSet { defaults.set(excluded, forKey: Keys.excluded) }
    }

    enum Keys {
        static let enabled = "clipEnabled", limit = "clipLimit", excluded = "clipExcluded"
    }
    static let defaultExcluded = ["com.1password.1password", "com.apple.keychainaccess"]
    /// 密码管理器等标记的敏感 / 临时内容（nspasteboard.org 约定）
    static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type", "com.nspasteboard.ConcealedType",
    ]

    let defaults: UserDefaults
    var pasteboard: NSPasteboard
    var lastChangeCount: Int
    var timer: Timer?
    var thumbs: [String: NSImage] = [:]

    public init(dir: URL, defaults: UserDefaults = .standard, pasteboard: NSPasteboard = .general) {
        self.defaults = defaults
        self.pasteboard = pasteboard
        enabled = defaults.object(forKey: Keys.enabled) as? Bool ?? true
        let lim = ClipboardStore.clampLimit(defaults.object(forKey: Keys.limit) as? Int ?? ClipboardStore.defaultLimit)
        limit = lim
        excluded = defaults.stringArray(forKey: Keys.excluded) ?? Self.defaultExcluded
        // 启动前就在剪贴板里的内容不算新复制
        lastChangeCount = pasteboard.changeCount
        let st = ClipboardStore(dir: dir, limit: lim)
        store = st
        items = st.items
    }

    // MARK: 监听

    /// 约 0.5s 轮询一次 changeCount（不需要任何系统权限，C11）
    public func start() {
        guard timer == nil else { return }
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    public func stop() { timer?.invalidate(); timer = nil }

    func poll() {
        let c = pasteboard.changeCount
        guard c != lastChangeCount else { return }
        lastChangeCount = c
        ingest(frontBundleID: NSWorkspace.shared.frontmostApplication?.bundleIdentifier)
    }

    /// 读当前剪贴板并记录；返回新增 / 提前的条目，跳过时返回 nil
    @discardableResult
    func ingest(frontBundleID: String?) -> ClipItem? {
        guard enabled else { return nil }
        if let b = frontBundleID, excluded.contains(b) { return nil }
        let types = (pasteboard.types ?? []).map(\.rawValue)
        if types.contains(where: { Self.skipTypes.contains($0) }) { return nil }

        var added: ClipItem?
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            added = store.addFiles(urls.map(\.path))
        } else if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            added = store.addText(text)
        } else if let (png, w, h) = Self.pngData(pasteboard) {
            added = store.addImage(png: png, width: w, height: h)
        }
        if added != nil { items = store.items }
        return added
    }

    static func pngData(_ pb: NSPasteboard) -> (Data, Int, Int)? {
        let data = pb.data(forType: .png) ?? pb.data(forType: .tiff)
        guard let data, let rep = NSBitmapImageRep(data: data) else { return nil }
        let png = pb.data(forType: .png) ?? rep.representation(using: .png, properties: [:])
        guard let png else { return nil }
        return (png, rep.pixelsWide, rep.pixelsHigh)
    }

    // MARK: 操作

    /// ⏎：把条目写回系统剪贴板（下次轮询读到同一内容时按去重提到最前）
    public func copy(_ item: ClipItem) {
        let pb = pasteboard
        pb.clearContents()
        switch item.kind {
        case .text:
            pb.setString(item.text ?? "", forType: .string)
        case .image:
            if let u = store.imageURL(item), let data = try? Data(contentsOf: u) {
                pb.setData(data, forType: .png)
                if let tiff = NSImage(data: data)?.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
            }
        case .files:
            pb.writeObjects((item.paths ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        }
        log.info("clip copied back kind=\(item.kind.rawValue, privacy: .public)")
    }

    public func delete(_ item: ClipItem) {
        thumbs[item.id] = nil
        store.delete(id: item.id)
        items = store.items
    }

    /// 清空历史：列表为空、存储文件夹不留残留（C10）
    public func clear() {
        thumbs = [:]
        store.clear()
        items = store.items
    }

    public func filter(_ q: String) -> [ClipItem] { ClipFilter.filter(items, q) }

    public func image(_ item: ClipItem) -> NSImage? {
        if let i = thumbs[item.id] { return i }
        guard let u = store.imageURL(item), let img = NSImage(contentsOf: u) else { return nil }
        thumbs[item.id] = img
        return img
    }

    /// 「位置 · 大小」
    public func fileDetail(_ item: ClipItem) -> String {
        guard let p = item.paths?.first else { return "" }
        let dir = ((p as NSString).deletingLastPathComponent as NSString).lastPathComponent
        if (item.paths?.count ?? 0) > 1 { return dir }
        let size = (try? FileManager.default.attributesOfItem(atPath: p)[.size] as? NSNumber)?.int64Value
        return size.map { "\(dir) · \(ClipTime.size($0))" } ?? dir
    }

    // MARK: 排除名单显示

    public static func appName(_ bundleID: String) -> String {
        if let u = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID) {
            return FileManager.default.displayName(atPath: u.path).replacingOccurrences(of: ".app", with: "")
        }
        switch bundleID {
        case "com.1password.1password": return "1Password"
        case "com.apple.keychainaccess": return "钥匙串访问"
        default: return bundleID
        }
    }

    public static func appIcon(_ bundleID: String) -> NSImage? {
        NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID).map { NSWorkspace.shared.icon(forFile: $0.path) }
    }
}
